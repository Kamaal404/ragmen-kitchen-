"""Abstract graph store interface."""

from __future__ import annotations

from abc import ABC, abstractmethod
from types import TracebackType
from typing import Any


class GraphStore(ABC):
    @abstractmethod
    def write_chunk(self, chunk: Any, source: Any) -> None: ...
    @abstractmethod
    def write_entity(self, entity: Any, chunk_id: str, source_id: str, blueprint_hash: str) -> None: ...
    @abstractmethod
    def write_relation(self, relation: Any, chunk_id: str, blueprint_hash: str) -> None: ...
    @abstractmethod
    def write_embedding(self, node_id: str, label: str, embedding: list[float], blueprint_hash: str) -> None: ...
    @abstractmethod
    def create_indexes(self) -> None: ...
    @abstractmethod
    def set_blueprint_active(self, blueprint_hash: str) -> None: ...
    @abstractmethod
    def retract_source(self, source_id: str) -> None: ...
    @abstractmethod
    def get_relations(self) -> list[dict]: ...
    @abstractmethod
    def get_source_uri(self, source_id: str) -> str: ...
    @abstractmethod
    def get_all_source_uris(self) -> dict[str, str]: ...
    @abstractmethod
    def get_chunks_by_blueprint(self, blueprint_hash: str) -> list: ...
    @abstractmethod
    def get_entity_ids(self) -> set[str]: ...
    @abstractmethod
    def close(self) -> None: ...

    def __enter__(self) -> GraphStore:
        return self

    def __exit__(self, exc_type: type[BaseException] | None, exc_val: BaseException | None, exc_tb: TracebackType | None) -> None:
        self.close()